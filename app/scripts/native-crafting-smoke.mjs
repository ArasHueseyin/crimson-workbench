// Tests only the separately launched hidden Workbench instance, never the game.
import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const output=resolve('../.local/phase3-native');await mkdir(output,{recursive:true});
let browser;
for(let i=0;i<30;i++){try{browser=await chromium.connectOverCDP('http://127.0.0.1:9225',{timeout:1500});break;}catch{await new Promise(r=>setTimeout(r,500));}}
if(!browser)throw Error('Hidden Workbench WebView2 not reachable');
const page=browser.contexts().flatMap(c=>c.pages()).find(p=>!p.url().startsWith('devtools:'));
if(!page)throw Error('No hidden workbench page');
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.locator('.workbench[data-ready="true"]').waitFor({timeout:90000});
await page.getByRole('button',{name:'Herstellungsplan',exact:true}).click();
await expect(page.getByLabel('Herstellungsziel')).toHaveValue('50001',{timeout:60000});
await expect(page.locator('.craft-status')).toContainText('Materialbedarf berechnet',{timeout:60000});
await page.getByLabel('Zielmenge').fill('31');
await expect(page.locator('[data-material-key="710001"] summary b')).toHaveText('10');
await page.getByLabel('Vorrat Bauholz 710001').fill('3');
await expect(page.locator('[data-material-key="710001"] summary b')).toHaveText('7');
await expect(page.locator('[data-material-key="720001"] summary b')).toHaveText('2');
await expect(page.locator('.craft-tree-card>.craft-node>.craft-node-head')).toContainText('60 Stück');
await expect(page.locator('.craft-target-picked img')).toBeVisible({timeout:15000});
await page.screenshot({path:resolve(output,'crafting-arrows.png')});
await page.getByLabel('Herstellungsziel').selectOption('1002066');
await page.getByLabel('Zielmenge').fill('1');
await page.getByLabel('Rezept für 1002066').selectOption('343');
await expect(page.getByLabel('Zutat 343:group:0')).toBeVisible();
await expect(page.locator('.craft-status')).toContainText('Materialbedarf berechnet');
const alternatives=await page.getByLabel('Zutat 343:group:0').locator('option').count();
if(alternatives<20)throw Error('Material group was not resolved');
await page.getByLabel('Zutat 343:group:0').selectOption('29801');
await expect(page.locator('.craft-status')).toContainText('Materialbedarf berechnet');
await expect(page.locator('[data-material-key="29801"]')).toBeVisible();
await page.screenshot({path:resolve(output,'crafting-soup.png')});
await page.setViewportSize({width:1024,height:768});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Crafting horizontal overflow');
await page.screenshot({path:resolve(output,'crafting-1024.png')});
await page.setViewportSize({width:1440,height:920});
await page.getByRole('button',{name:/Itemdatenbank/}).click();
await page.getByRole('textbox',{name:'Items suchen'}).fill('Arrow');
await page.locator('[data-item-key="50001"]').waitFor({timeout:60000});
await page.locator('[data-item-key="50001"]').click();
await page.getByRole('tab',{name:'Verknüpfungen',exact:true}).click();
await page.getByRole('button',{name:/Herstellen:/}).first().waitFor({timeout:60000});
await page.getByRole('button',{name:/Herstellen:/}).first().click();
await expect(page.getByLabel('Herstellungsziel')).toHaveValue('50001');
await expect(page.getByLabel('Vorrat Bauholz 710001')).toHaveValue('3');
if(errors.length)throw Error(errors.join('\n'));
const result={native:true,arrowTarget:31,arrowProduced:60,woodOwned:3,woodMissing:7,ironMissing:2,soupRecipe:343,materialAlternatives:alternatives,itemRecipeLinks:true,width1024:true,pageErrors:errors};
