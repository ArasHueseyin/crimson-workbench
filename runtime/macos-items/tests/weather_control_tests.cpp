#include "../src/world/world_control.h"
#include <cassert>
using namespace crimson::mac_items;
using namespace crimson::marketplace::world_controls;
int main(){
    WeatherControl control;Reply status;status.generation=1;status.flags=time_frozen;
    WeatherFrame frame;frame.ready=true;frame.fingerprint=123;frame.settings={0,.6f,.4f,3,.007f,.4f,.25f,25};
    const auto automatic=frame.settings;
    unsigned applies{},manuals{},phases{};
    auto apply=[&](const WeatherSettings& value,bool acquire){++applies;frame.settings=value;if(acquire)frame.view.manual=true;return WeatherPublication::published;};
    auto manual=[&](bool value){++manuals;frame.view.manual=value;return WeatherPublication::published;};
    auto phase=[&](float value){++phases;frame.settings.phase=value;return WeatherPublication::published;};
    auto tick=[&](std::uint64_t now,bool fresh=true){control.producer(status,frame,now,fresh,apply,manual,phase);};
    auto original=[&]{const bool rain=frame.settings.phase>0;frame.rain=rain?frame.settings.precipitation:0;
        frame.snow=rain?0:frame.settings.precipitation;frame.settings.phase=25;};
    tick(100);assert(status.flags&weather_available);assert(applies==0&&manuals==0);
    Request request;request.id=1;request.generation=1;request.not_after_ms=1000;
    request.operation=ControlOperation::choose_weather;request.weather={.3f,.7f,.5f,4,.01f,PrecipitationPhase::snow};
    control.enqueue(request);tick(101);
    assert(applies==1&&frame.view.manual&&status.weather_result==ControlCode::queued);
    original();tick(102);
    assert(status.weather_result==ControlCode::published&&status.weather_receipt==1&&status.weather.phase==PrecipitationPhase::snow);
    assert(frame.settings.phase==-1&&status.flags&time_frozen);
    request.id=2;request.operation=ControlOperation::freeze_weather;request.enabled=1;
    control.enqueue(request);original();tick(103);original();tick(104);
    assert(status.weather_result==ControlCode::published&&status.flags&weather_frozen);
    request.id=3;request.enabled=0;control.enqueue(request);original();tick(105);
    assert(!(status.flags&weather_frozen)&&frame.view.manual&&manuals==0);
    request.id=4;request.operation=ControlOperation::release_weather;control.enqueue(request);original();tick(106);
    assert(!frame.view.manual&&manuals==1&&status.weather_result==ControlCode::queued);
    frame.settings=automatic;original();tick(107);
    assert(status.weather_result==ControlCode::released&&status.weather_receipt==4&&status.flags&time_frozen);
    request.id=5;request.operation=ControlOperation::choose_weather;control.enqueue(request);tick(108);original();tick(109);
    auto before=applies;auto before_phase=phases;frame.settings.wind=8;tick(110);
    assert(applies==before&&phases==before_phase&&status.reason==ControlReason::foreign_change&&!(status.flags&weather_available));
    WeatherControl foreign;Reply blocked;blocked.generation=1;frame.view.manual=true;
    foreign.producer(blocked,frame,200,true,apply,manual,phase);
    assert(!(blocked.flags&weather_available)&&applies==before);
    assert(blocked.weather_reason==static_cast<unsigned>(ControlReason::foreign_change));
    WeatherControl uncertain;Reply failed;failed.generation=1;failed.flags=time_frozen;frame.view.manual=false;
    uncertain.enqueue(request);
    uncertain.producer(failed,frame,300,true,[&](const WeatherSettings&,bool){++applies;return WeatherPublication::uncertain;},manual,phase);
    assert(failed.weather_result==ControlCode::uncertain&&failed.flags&weather_uncertain&&failed.flags&time_frozen);
    before=applies;uncertain.producer(failed,frame,301,true,apply,manual,phase);assert(applies==before);
    WeatherControl expired;Reply old;old.generation=1;request.id=6;request.not_after_ms=100;
    expired.enqueue(request);expired.producer(old,frame,400,true,apply,manual,phase);
    assert(old.weather_result==ControlCode::expired&&applies==before);
    WeatherControl changed;Reply world;world.generation=1;request.id=7;request.not_after_ms=1000;
    changed.enqueue(request);changed.producer(world,frame,500,true,apply,manual,phase);original();
    changed.producer(world,frame,501,true,apply,manual,phase);++world.generation;
    changed.producer(world,frame,502,true,apply,manual,phase);
    assert(!frame.view.manual&&world.weather_result==ControlCode::published);
    frame.settings=automatic;changed.producer(world,frame,503,true,apply,manual,phase);
    assert(world.code==ControlCode::released);
    WorldControl combined(99);
    TimeContext clock{7,8,0,{50,12,0,0,0,1,0,12,1000},{50,12,0,0,0,1,0,12,1000},1000};
    auto publish_clock=[&](const TimeContext&,const FieldTime& value){clock.raw=value;clock.time=value;return TimePublication::published;};
    combined.observe(clock,1000,publish_clock);frame.view.manual=false;frame.settings=automatic;original();
    combined.weather_producer(frame,1000,7,apply,manual,phase);
    auto snapshot=combined.handle({},1000,7);assert((snapshot.flags&3)==3);
    Request weather_request;weather_request.id=1;weather_request.session=99;weather_request.generation=1;weather_request.not_after_ms=2000;
    weather_request.operation=ControlOperation::choose_weather;weather_request.weather={.2f,.5f,.3f,4,.01f,PrecipitationPhase::rain};
    assert(combined.handle(weather_request,1000,7).code==ControlCode::queued);
    auto time_request=weather_request;time_request.id=2;time_request.operation=ControlOperation::freeze_time;time_request.enabled=1;
    assert(combined.handle(time_request,1000,7).code==ControlCode::queued);
    combined.weather_producer(frame,1001,7,apply,manual,phase);original();
    combined.observe(clock,1002,publish_clock);combined.weather_producer(frame,1003,7,apply,manual,phase);
    snapshot=combined.handle({},1003,7);
    assert(snapshot.time_receipt==2&&snapshot.weather_receipt==1&&snapshot.time_result==ControlCode::published
        &&snapshot.weather_result==ControlCode::published&&snapshot.flags&time_frozen);
    assert(combined.handle(weather_request,1004,7).reason==ControlReason::replay);
    weather_request.id=3;weather_request.operation=ControlOperation::release_weather;
    assert(combined.handle(weather_request,1004,7).code==ControlCode::queued);
    combined.weather_producer(frame,1005,7,apply,manual,phase);frame.settings=automatic;original();
    combined.weather_producer(frame,1006,7,apply,manual,phase);
    snapshot=combined.handle({},1006,7);assert(snapshot.weather_result==ControlCode::released&&snapshot.flags&time_frozen);
    assert(!(combined.handle({},1006,9).flags&3));
}
